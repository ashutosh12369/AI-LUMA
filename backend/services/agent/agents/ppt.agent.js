// [What] Design Tokens (colors) ka ek object bana rahe hain (THEME).
// [Why] UI/UX consistency maintain karne ke liye. Jab bhi PPT me color use hoga, hardcode hex values ki jagah THEME object se reference lenge. Agar kal ko theme change karni ho, toh sirf yahan update karna padega.
const THEME = {
  dark:    "0F172A",   // cover / conclusion bg
  primary: "2563EB",   // accent color
  white:   "FFFFFF",
  offWhite:"F8FAFC",
  text:    "1E293B",
  muted:   "64748B",
  card:    "EFF6FF",   // light card bg
};

// [What] 'addCoverSlide' naam ka helper function bana rahe hain.
// [Why] Code reusability ke liye. Cover slide (pehle slide) ka design complex hota hai, isliye isko alag function me rakha gaya hai taaki main logic clean rahe.
function addCoverSlide(ppt, title, subtitle) {
  // [What] ppt object me ek nayi slide add kar rahe hain aur uska background set kar rahe hain.
  // [Why] Har slide ek blank canvas se shuru hoti hai. Dark theme cover page ko premium look deta hai.
  const slide = ppt.addSlide();
  slide.background = { color: THEME.dark };

  // [What] Top-right corner me ek large translucent circle (shape) add kar rahe hain.
  // [Why] Visual appeal badhane ke liye (decorative elements). Transparency se modern design aesthetic aata hai.
  slide.addShape(ppt.ShapeType.ellipse, {
    x: 10.5, y: -1.2, w: 4, h: 4,
    fill: { color: THEME.primary, transparency: 75 },
    line: { color: THEME.primary, transparency: 75 },
  });

  // [What] Bottom-left corner me ek chhota circle add kar rahe hain.
  // [Why] Design me balance create karne ke liye. Ye sab coordinates (x, y) inches me hote hain presentation slide me.
  slide.addShape(ppt.ShapeType.ellipse, {
    x: -0.8, y: 5.5, w: 2.5, h: 2.5,
    fill: { color: THEME.primary, transparency: 80 },
    line: { color: THEME.primary, transparency: 80 },
  });

  // [What] Slide par main Title add kar rahe hain.
  // [Why] User ka topic ya main heading show karne ke liye. Font size bada (36) aur bold rakha hai visual hierarchy ke liye.
  slide.addText(title, {
    x: 0.7, y: 2.0, w: 11.9, h: 1.2,
    fontSize: 36, bold: true, color: THEME.white,
    fontFace: "Calibri", align: "center",
  });

  // [What] Agar subtitle (tagline) provided hai toh usko title ke neeche add kar rahe hain.
  // [Why] Extra context dene ke liye. Ye optional parameter ho sakta hai isliye if condition check kar rahe hain.
  if (subtitle) {
    slide.addText(subtitle, {
      x: 0.7, y: 3.4, w: 11.9, h: 0.5,
      fontSize: 16, color: "94A3B8",
      fontFace: "Calibri", align: "center",
    });
  }

  // [What] Slide ke bottom me footer label ("Generated by AI-LUMA") daal rahe hain.
  // [Why] Branding aur watermark ke liye, taaki pata chale presentation kahan se bani hai.
  slide.addText("Generated by AI-LUMA", {
    x: 0.7, y: 6.7, w: 11.9, h: 0.25,
    fontSize: 10, color: "475569",
    fontFace: "Calibri", align: "center",
  });
}

// [What] 'addBulletSlide' helper function bana rahe hain.
// [Why] Ye common slide type hai jisme content bullet points me hota hai. Ye repeatedly use hoga, isliye function zaroori hai.
function addBulletSlide(ppt, slideIndex, title, bullets) {
  // [What] Nayi slide add kar rahe hain pichle background ke sath.
  // [Why] Content slides usually bright/white background wali hoti hain for readability.
  const slide = ppt.addSlide();
  slide.background = { color: THEME.white };

  // [What] Top-right corner me slide number badge bana rahe hain.
  // [Why] Professional presentations me slide numbers navigation and reference ke liye important hote hain.
  slide.addShape(ppt.ShapeType.ellipse, {
    x: 12.5, y: 0.15, w: 0.45, h: 0.45,
    fill: { color: THEME.primary },
    line: { color: THEME.primary },
  });
  slide.addText(`${slideIndex}`, {
    x: 12.5, y: 0.15, w: 0.45, h: 0.45,
    fontSize: 10, bold: true, color: THEME.white,
    fontFace: "Calibri", align: "center", valign: "middle",
  });

  // [What] Slide ka header/title add kar rahe hain.
  // [Why] Slide ka main topic define karne ke liye.
  slide.addText(title, {
    x: 0.6, y: 0.25, w: 11.6, h: 0.65,
    fontSize: 28, bold: true, color: THEME.primary,
    fontFace: "Calibri",
  });

  // [What] Title ke just neeche ek horizontal line (divider) add kar rahe hain.
  // [Why] Title ko main content se visually separate karne ke liye (aesthetic purpose).
  slide.addShape(ppt.ShapeType.line, {
    x: 0.6, y: 0.95, w: 11.8, h: 0,
    line: { color: "CBD5E1", width: 1.5 },
  });

  // [What] Bullet cards layout variables set kar rahe hain (height, startY, gap).
  // [Why] Har bullet point ko render karne se pehle positions calculate karni hoti hain taki overlap na ho.
  const cardH = 0.72;
  const startY = 1.15;
  const gap = 0.12;

  // [What] Bullets array pe loop lagakar maximum 6 points (using slice) render kar rahe hain.
  // [Why] 6 se jyada points ek slide me overcrowd ho jate hain aur layout bigad jata hai.
  bullets.slice(0, 6).forEach((txt, i) => {
    const y = startY + i * (cardH + gap);

    // [What] Har bullet ke peeche ek Rounded Rectangle shape bana rahe hain. Alternate colors use kar rahe hain (i % 2).
    // [Why] Simple text list ki jagah "card-style" list jyada modern lagti hai. Alternate colors padhne me asani (zebra striping) dete hain.
    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.6, y, w: 11.8, h: cardH,
      fill: { color: i % 2 === 0 ? THEME.card : THEME.offWhite },
      line: { color: "DBEAFE" },
      rectRadius: 0.08,
    });

    // [What] Text se pehle ek custom circular bullet dot add kar rahe hain.
    // [Why] Default bullets boring ho sakte hain, theme ke colors ke hisaab se custom shape draw karna better design deta hai.
    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.85, y: y + 0.24, w: 0.22, h: 0.22,
      fill: { color: THEME.primary },
      line: { color: THEME.primary },
    });

    // [What] Actual bullet text add kar rahe hain inside the rectangle.
    // [Why] Data ko display karne ke liye. Vertically center (valign) align rakha hai card ke andar.
    slide.addText(txt, {
      x: 1.2, y: y + 0.1, w: 10.9, h: cardH - 0.2,
      fontSize: 14, color: THEME.text,
      fontFace: "Calibri", valign: "middle",
    });
  });

  // [What] Footer me brand name add kar rahe hain.
  // [Why] Consistency ke liye har content slide me chhota watermark.
  slide.addText("AI-LUMA", {
    x: 0.6, y: 7.0, w: 2, h: 0.2,
    fontSize: 9, color: THEME.muted, fontFace: "Calibri",
  });
}

// [What] 'addStatSlide' helper function bana rahe hain.
// [Why] Ye special slide type hai jo data/numbers ko highlight karne ke liye use hota hai (metrics slide).
function addStatSlide(ppt, slideIndex, title, stats) {
  // [What] Dark background slide add kar rahe hain.
  // [Why] Stats/numbers dark background par pop karte hain aur user ka attention direct numerical values par jata hai.
  const slide = ppt.addSlide();
  slide.background = { color: THEME.dark };

  // [What] Slide Title add kar rahe hain.
  // [Why] Stats ka context dene ke liye (e.g., "Company Growth").
  slide.addText(title, {
    x: 0.6, y: 0.3, w: 12, h: 0.65,
    fontSize: 28, bold: true, color: THEME.white,
    fontFace: "Calibri",
  });
  
  // [What] Divider line draw kar rahe hain primary color me.
  // [Why] Title aur content separation ke liye.
  slide.addShape(ppt.ShapeType.line, {
    x: 0.6, y: 1.0, w: 11.8, h: 0,
    line: { color: THEME.primary, width: 2 },
  });

  // [What] Columns count calculate kar rahe hain (max 4 columns, warna stats ki length jitne).
  // [Why] Horizontal space limit hoti hai. Agar 3 items hain toh width dynamically divide hogi, par 4 se zyada stats permit nahi hain ui break hone se rokne k lie.
  const cols = stats.length <= 3 ? stats.length : 4;
  const cardW = 11.8 / cols;
  const startX = 0.6;

  // [What] Stats array pe loop chalakar maximum 4 cards draw kar rahe hain.
  // [Why] Har stat ko ek prominent 'card' me dikhana numbers ko easily readable banata hai dashboard style me.
  stats.slice(0, 4).forEach((s, i) => {
    const x = startX + i * cardW;
    
    // [What] Stat background card draw kar rahe hain.
    // [Why] Data ko frame karne ke liye.
    slide.addShape(ppt.ShapeType.roundRect, {
      x: x + 0.1, y: 1.5, w: cardW - 0.2, h: 3.8,
      fill: { color: "1E3A5F" },
      line: { color: THEME.primary, width: 1 },
      rectRadius: 0.12,
    });
    
    // [What] Bada number/value (jaise "42%") center me add kar rahe hain.
    // [Why] Value sabse important hai is slide type me, isliye fontSize 40 diya gaya hai.
    slide.addText(s.value, {
      x: x + 0.1, y: 1.9, w: cardW - 0.2, h: 1.5,
      fontSize: 40, bold: true, color: THEME.primary,
      fontFace: "Calibri", align: "center",
    });
    
    // [What] Label/description add kar rahe hain (jaise "Revenue Growth").
    // [Why] Number kya represent karta hai ye batane ke liye (subtext).
    slide.addText(s.label, {
      x: x + 0.1, y: 3.5, w: cardW - 0.2, h: 1.4,
      fontSize: 14, color: "CBD5E1",
      fontFace: "Calibri", align: "center",
    });
  });

  // [What] Standard branding footer daal rahe hain.
  // [Why] Slides me uniformity maintain karne ke liye.
  slide.addText("AI-LUMA", {
    x: 0.6, y: 7.0, w: 2, h: 0.2,
    fontSize: 9, color: THEME.muted, fontFace: "Calibri",
  });
}

// [What] 'addConclusionSlide' function bana rahe hain presentation end karne ke liye.
