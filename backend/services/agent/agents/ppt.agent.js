// [What] LLM se mile text output ko structured object (JSON like) me convert karne ke liye function.
// [Why] LLM unstructured text generate karta hai. Code ko PPT banane ke liye structured arrays aur strings chahiye (jaise title kya hai, bullet points kya hain). ParseResponse us bridge ka kaam karta hai.
function parseResponse(content) {
  // [What] Ek base result structure initialize kar rahe hain.
  // [Why] Taaki agar regex match na ho ya parse fail ho, to code crash na kare blki default empty structure return kare.
  const result = {
    title: "",
    subtitle: "",
    slides: [],
  };

  // [What] Regex se TITLE line dhundh rahe hain.
  // [Why] System prompt ne AI ko "TITLE: xyz" format me respond karne ko bola hai. Ye regex us value ko extract karti hai.
  const titleMatch = content.match(/^TITLE:\s*(.+)/m);
  result.title = titleMatch?.[1]?.trim() || "Presentation";

  // [What] Regex se SUBTITLE extract kar rahe hain.
  // [Why] Cover page design ke liye required hai. Optional chain (?.) error se bachati hai agar subtitle nahi mila.
  const subtitleMatch = content.match(/^SUBTITLE:\s*(.+)/m);
  result.subtitle = subtitleMatch?.[1]?.trim() || "";

  // [What] Pure content ko "SLIDE:" keyword se split kar rahe hain.
  // [Why] Har slide ka chunk alag alag process kiya ja sake. .slice(1) ka use pehle header wale part (title/subtitle) ko hatane ke liye kiya hai.
  const rawSlides = content.split(/^SLIDE:/m).slice(1);

  // [What] Har ek raw slide text pe loop chala rahe hain.
  // [Why] Har text block ko analyze karke uski type aur content object form me dalna hai.
  rawSlides.forEach((raw) => {
    // [What] Slide text ko newline se todte hain aur empty lines filter karte hain.
    // [Why] Line-by-line processing easily karne ke liye.
    const lines = raw.split("\n").map(l => l.trim()).filter(Boolean);
    
    // [What] Aisi line dhundhte hain jo "Title:" ya "Type:" se start hoti ho.
    // [Why] Slide ka metadata extract karne ke liye (kya type hai, kya title hai).
    const titleLine = lines.find(l => l.startsWith("Title:"));
    const typeLine  = lines.find(l => l.startsWith("Type:"));

    // [What] Labels remove karke actual values store kar rahe hain (defaults fallback ke sath).
    // [Why] Agar AI proper format miss kar de, tabhi fallback defaults ("Slide", "bullets") system crash hone se bachate hain.
    const title = titleLine?.replace("Title:", "").trim() || "Slide";
    const type  = typeLine?.replace("Type:", "").trim().toLowerCase() || "bullets";

    // [What] Jo lines dash (-) se start ho rahi hain unko items (bullets) me store kar rahe hain.
    // [Why] Markdown lists extract karke frontend arrays me map karne ke liye.
    const items = lines
      .filter(l => l.startsWith("- "))
      .map(l => l.replace(/^-\s*/, "").trim());

    // [What] Stats type slides ke liye bullet points me pipe (|) split kar rahe hain.
    // [Why] Kyunki stats format "Label | Value" tha (e.g. "Users | 1M"). Ise key-value object {label, value} me convert karna zaruri hai.
    const stats = items.map(i => {
      const parts = i.split("|").map(p => p.trim());
      return parts.length === 2
        ? { label: parts[0], value: parts[1] }
        : { label: i, value: "" };
    });

    // [What] Ek complete slide object array me push kar rahe hain.
    // [Why] Result ready hone pe ye object easily forEach loop me daal kar PptxgenJS functions ko pass kiya jayega.
    result.slides.push({ title, type, items, stats });
  });

  // [What] Final structured data wapas bhej rahe hain.
  // [Why] Taaki calling function is object ka directly use kar sake PPT generate karne ke liye.
  return result;
}

// [What] Main asynchronous PPT Agent function export kar rahe hain.
// [Why] Ye main entry point hai jo state input lega, user ki limits check karega, AI se generate karwayega, PPT draw karke aws par upload karega.
export const pptAgent = async (state) => {
  try {
    // [What] User ka rate limit check kar rahe hain 'ppt' action ke liye.
    // [Why] Security aur business logic. Free users ko abuse se rokne ke liye ye check ensures ki unke paas allowed attempts bache hain. (Throws error agar limit cross ho jaye).
    await checkAgentLimit(
        state.userId,
        "ppt"
    );

    // [What] User ke balance se credits deduct kar rahe hain is premium PPT generation action ke liye.
    // [Why] Billing mechanism handle karne ke liye. Har generation ka cost hoga API aur S3 resources ki wajah se.
    await deductCredits(
        state.userId,
        "ppt"
    ); 

    // [What] "ppt" type ke liye configure kiya gaya LLM instance utha rahe hain.
    // [Why] Ye specific model ho sakta hai (e.g. gpt-4) jo formatted text aur strict templates jyada achhe se follow karta ho.
    const llm = getModel("ppt");

    // [What] LLM ko prompt bhej rahe hain presentation ka content likhne ke liye, ek strict output template ke sath.
    // [Why] "Few-shot prompting" ya strict system instructions di ja rahi hain. Bina is format ke, regex based parseResponse function fail ho jayega. Hum AI ko force kar rahe hain fixed DSL (Domain Specific Language) me reply karne ko.
    const aiResponse = await llm.invoke(` 
Create a professional PowerPoint presentation on the topic below.

Topic: ${state.prompt}

Output Rules:
- No markdown, no explanation, only the format below.
- Generate exactly 8 slides after the title.
- Slide types: bullets | stats | conclusion
  - bullets: 4-6 bullet points (most slides)
  - stats: 3-4 key metrics as "Label | Value" (use once for impact)
  - conclusion: 3-4 short takeaway points (last slide)

Format:

TITLE: Presentation Title
SUBTITLE: One-line tagline or description

SLIDE:
Type: bullets
Title: Introduction
- Point one
- Point two
- Point three
- Point four

SLIDE:
Type: stats
Title: Key Numbers
- Users Reached | 10M+
- Revenue Growth | 42%
- Countries | 30+

SLIDE:
Type: conclusion
Title: Conclusion
- Key takeaway one
- Key takeaway two
- Key takeaway three
`);

    // [What] Raw string response ko structured object me convert karte hain helper pass karke.
    // [Why] Kyunki javascript library (pptxgen) string samajh ke draw nahi karegi, usse functions ko call karne ke liye objects arrays chaiye (jaise arrays of bullets).
    const content = aiResponse.content.trim();
    const parsed  = parseResponse(content);

    // [What] Pptxgen class ka naya instance banate hain jisme default meta-data dalte hain.
    // [Why] Ye final presentation file (document object) banne ka process shuru karta hai, default 16:9 widescreen layout (LAYOUT_WIDE) ka set karta hai.
    const ppt = new pptxgen();
    ppt.layout  = "LAYOUT_WIDE";
    ppt.author  = "AI-LUMA";
    ppt.subject = state.prompt;
    ppt.title   = parsed.title;

    // [What] Cover slide helper ko call kar rahe hain extracted title/subtitle ke sath.
    // [Why] Presentation ka first impression build karne ke liye jo parse data se liya gaya hai.
    addCoverSlide(ppt, parsed.title, parsed.subtitle);

    // [What] Parse kiye hue slides ke array pe loop chalakar appropriate helper ko invoke kar rahe hain slide type ke basis par.
    // [Why] Dynamic PPT rendering engine! AI jaisa type define karega (stats, conclusion, default bullets), waisa function use hoga slide ko UI component ki tarah design karne ke liye.
    parsed.slides.forEach((slide, i) => {
      const num = i + 1; // 1-indexed slide number
      if (slide.type === "stats") {
        addStatSlide(ppt, num, slide.title, slide.stats);
      } else if (slide.type === "conclusion") {
        addConclusionSlide(ppt, slide.title, slide.items);
      } else {
        addBulletSlide(ppt, num, slide.title, slide.items);
      }
    });

    // [What] Final file name generate kar rahe hain unique timestamp ka use karke.
    // [Why] Taaki S3 bucket me duplicate files ka collision na ho aur data overwrite na ho.
    const fileName = `ppt-${Date.now()}.pptx`;

    // [What] PPT instance ko memory me "nodebuffer" binary format me write karte hain.
    // [Why] Node.js backend environment me disk IO directly karne ki jagah hum buffer banate hain jise turant cloud stream / AWS ko bheja ja sake.
    const buffer = await ppt.write({
      outputType: "nodebuffer"
    });

    // [What] Custom utility use karke S3 (Cloud Storage) me Buffer data upload kar rahe hain proper MIME type ke sath.
    // [Why] Presentation file user machine pe bhejne ke bajaye cloud me permanently/temporarily host hoti hai jahan se public URL banega.
    await uploadToS3(
      buffer,
      fileName,
      "application/vnd.openxmlformats-officedocument.presentationml.presentation"
    );

    // [What] Uploaded file ke liye signed/temporary download link create karte hain jo 24 ghante (24*60*60s) tak valid rahega.
    // [Why] Security ke liye. S3 object ko public rakhne ki jagah presigned URL dete hain taaki unauthorized access na ho.
    const downloadUrl = await getDownloadUrl(
      fileName,
      24*60*60
    );

    // [What] Updated state return karte hain jisme final markdown response shamil hai.
    // [Why] RAG ya Bot framework final UI message me is state ko padhta hai aur download link render karta hai clickable button ki tarah.
    return {
      ...state,
      response: ` 
# Presentation Generated Successfully

 **${parsed.title}**

 [Download PPT](${downloadUrl})

 Link expires in 24 hours.
`
    };
  } catch (error) {
    // [What] Kisi bhi error ko catch karke gracefully handle karte hain aur error message return karte hain.
    // [Why] Agar API rate limit hua ya S3 fail hua toh process crash hone ke badle user friendly message dikhaye bot frontend par.
    console.log("PPT Agent Error:", error);
    return { ...state, response: "Failed to generate presentation." };
  }
};